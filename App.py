def extract_issues_from_pdf(uploaded_file):
    extracted_issues = []
    if PDF_LIB is None:
        return extracted_issues, "مكتبة PyPDF2 غير مثبتة، يعمل النظام حالياً بقاعدة البيانات المدمجة."

    try:
        reader = PyPDF2.PdfReader(uploaded_file)
        full_text = ""
        for idx, page in enumerate(reader.pages):
            page_text = page.extract_text() or ""
            full_text += f"\n[صفحة {idx+1}]\n" + page_text

        pattern = re.compile(r'([٤٥٦٧4567][٠-٩0-9]{2})\s*-\s*([^\n]+(?:\n(?![٤٥٦٧4567][٠-٩0-9]{2}\s*-)[^\n]+)*)')
        matches = pattern.findall(full_text)

        for issue_num, body in matches:
            clean_body = re.sub(r'\s+', ' ', body).strip()
            matn_match = re.search(r'\(([^)]+)\)', clean_body)
            matn_text = f"({matn_match.group(1)})" if matn_match else clean_body[:140] + "..."

            tarjih_match = re.search(r'(وذهب بعض أهل العلم[^.]+(?:\.[^.]+)*?الأقرب[^.]*\.)', clean_body)
            tarjih_text = tarjih_match.group(1) if tarjih_match else "وافق الشارحُ المتنَ في أصل الحكم مع تحرير الدليل والتعليل."

            extracted_issues.append({
                "id": issue_num,
                "chapter": "مستخرج من ملف PDF المرفوع",
                "page": "من الملف",
                "matn": matn_text,
                "summary": [
                    f"المسألة رقم ({issue_num}) المستخرجة مباشرة من النص الأصلي.",
                    clean_body[:250] + ("..." if len(clean_body) > 250 else "")
                ],
                "matn_ruling": matn_text,
                "tarjih": tarjih_text,
                "illa": "انظر التعليل التفصيلي والأدلة المسندة في نص المسألة المستخرج.",
                "dispute": clean_body[:350] + ("..." if len(clean_body) > 350 else "")
            })
        return extracted_issues, f"تم بنجاح قراءة {len(reader.pages)} صفحة واستخراج {len(extracted_issues)} مسألة فقهية!"
    except Exception as e:
        return [], f"حدث خطأ أثناء تحليل الملف: {str(e)}"


def generate_infinite_question(knowledge_pool, chapter_filter="الكل"):
    filtered_pool = [
        item for item in knowledge_pool
        if chapter_filter == "الكل" or chapter_filter in item["chapter"]
    ]
    if not filtered_pool:
        filtered_pool = knowledge_pool

    target = random.choice(filtered_pool)
    other_items = [x for x in knowledge_pool if x["id"] != target["id"]]
    if len(other_items) < 3:
        other_items = knowledge_pool * 3

    distractors_source = random.sample(other_items, 3)
    question_types = ["tarjih", "illa", "matn_vs_sharh", "ruling"]
    q_type = random.choice(question_types)

    if q_type == "tarjih":
        question_stem = (
            f"في ({target['chapter']} - المسألة {target['id']}) قال المصنف في المتن: "
            f"«{target['matn']}».\nما هو **الترجيح الفقهي (الأقرب)** الذي اعتمده الشارح د. عبد الله بن جبرين في هذه المسألة؟"
        )
        correct_option = target["tarjih"]
        wrong_options = [
            f"الجزم بظاهر ما في المتن مطلقاً من غير استثناء ولا تفصيل: ({target['matn_ruling']}).",
            distractors_source[0]["tarjih"],
            distractors_source[1]["tarjih"]
        ]
    elif q_type == "illa":
        question_stem = (
            f"في ({target['chapter']} - المسألة {target['id']}) رجّح الشارح القول الآتي: "
            f"«{target['tarjih']}».\nما هي **العلة الفقهية والدليل** الذي استند إليه الشارح في هذا الترجيح؟"
        )
        correct_option = target["illa"]
        wrong_options = [
            distractors_source[0]["illa"],
            distractors_source[1]["illa"],
            "الاحتياط المحض للعبادة وتغليب جانب الحظر سداً للذريعة بلا نص خاص."
        ]
    elif q_type == "matn_vs_sharh":
        question_stem = (
            f"ورد في المتن في ({target['chapter']} - المسألة {target['id']}): «{target['matn']}».\n"
            f"أي العبارات التالية تمثل **مذهب المصنف في المتن** قبل النظر إلى ترجيح الشارح؟"
        )
        correct_option = target["matn_ruling"]
        wrong_options = [
            target["tarjih"],
            distractors_source[0]["matn_ruling"],
            distractors_source[1]["matn_ruling"]
        ]
    else:
        question_stem = (
            f"أي مسألة من المسائل التالية ينطبق عليها هذا التحرير الفقهي للخلاف: "
            f"«{target['dispute']}»؟"
        )
        correct_option = f"المسألة ({target['id']}) في {target['chapter']}: {target['matn']}"
        wrong_options = [
            f"المسألة ({distractors_source[0]['id']}) في {distractors_source[0]['chapter']}: {distractors_source[0]['matn']}",
            f"المسألة ({distractors_source[1]['id']}) في {distractors_source[1]['chapter']}: {distractors_source[1]['matn']}",
            f"المسألة ({distractors_source[2]['id']}) في {distractors_source[2]['chapter']}: {distractors_source[2]['matn']}"
        ]

    options = list(dict.fromkeys([correct_option] + wrong_options))
    while len(options) < 4:
        options.append(f"خيار فقهي آخر غير معتمد في المسألة ({random.randint(407, 781)}).")
    random.shuffle(options)

    return {
        "issue_obj": target,
        "question": question_stem,
        "options": options,
        "answer": correct_option
    }


