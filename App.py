def calculate_camel_zakat(count):
    if count < 5:
        return "لا زكاة فيها (أقل من النصاب وهو 5 من الإبل بالإجماع).", "وقص دون النصاب"
    elif count <= 9:
        return "شاة واحدة (جذعة ضأن أو ثنية معز).", f"الوقص: ما زاد على 5 إلى 9 ({count - 5} رؤوس)"
    elif count <= 14:
        return "شاتان.", f"الوقص: {count - 10} رؤوس"
    elif count <= 19:
        return "ثلاث شياه.", f"الوقص: {count - 15} رؤوس"
    elif count <= 24:
        return "أربع شياه.", f"الوقص: {count - 20} رؤوس"
    elif count <= 35:
        return "بنت مخاض (ما تم لها سنة)، فإن لم تكن عنده فابن لبون (ما تم له سنتان).", f"الوقص: {count - 25} رأساً"
    elif count <= 45:
        return "بنت لبون (ما تم لها سنتان).", f"الوقص: {count - 36} رأساً"
    elif count <= 60:
        return "حِقّة (ما تم لها ثلاث سنين وطرقتها الفحل).", f"الوقص: {count - 46} رأساً"
    elif count <= 75:
        return "جَذَعة (ما تم لها أربع سنين).", f"الوقص: {count - 61} رأساً"
    elif count <= 90:
        return "بنتا لبون (اثنتان من بنات اللبون).", f"الوقص: {count - 76} رأساً"
    elif count <= 120:
        return "حِقّتان (اثنتان من الحِقاق).", f"الوقص: {count - 91} رأساً"
    elif count <= 129:
        return "ثلاث بنات لبون (من 121 إلى 129).", f"الوقص: {count - 121} رأساً"
    else:
        tens = count // 10
        possible = []
        for huqqa in range((tens // 5) + 1):
            rem = tens - (huqqa * 5)
            if rem >= 0 and rem % 4 == 0:
                bint_labun = rem // 4
                parts = []
                if huqqa > 0:
                    parts.append(f"{huqqa} حِقّة")
                if bint_labun > 0:
                    parts.append(f"{bint_labun} بنت لبون")
                possible.append(" و ".join(parts))
        if possible:
            if len(possible) > 1:
                return f"يجتمع الفرضان فيخيّر المالك بين: ({' أو '.join(possible)}).", "قاعدة: في كل 50 حقة وفي كل 40 بنت لبون"
            return possible[0], "قاعدة: في كل 50 حقة وفي كل 40 بنت لبون"
        else:
            h = tens // 5
            b = (tens % 5) // 4
            return f"يُحسب على العقود: {h} حقة و {b} بنت لبون.", "ما زاد على 120"


def calculate_cattle_zakat(count):
    if count < 30:
        return "لا زكاة فيها حتى تبلغ ثلاثين بالإجماع."
    elif count < 40:
        return "تبيع أو تبيعة (ما تم له سنة)."
    elif count < 60:
        return "مُسِنّة (ما تم لها سنتان)."
    else:
        tens = count // 10
        options = []
        for musinna in range((tens // 4) + 1):
            rem = tens - (musinna * 4)
            if rem >= 0 and rem % 3 == 0:
                tabi = rem // 3
                desc = []
                if tabi > 0:
                    desc.append(f"{tabi} تبيع/تبيعة")
                if musinna > 0:
                    desc.append(f"{musinna} مسنة")
                options.append(" و ".join(desc))
        if options:
            return " أو ".join(options)
        return f"في كل ثلاثين تبيع وفي كل أربعين مسنة (عدد الرؤوس: {count})."


